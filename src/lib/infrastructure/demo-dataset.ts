const LOCAL_STORAGE_KEY = 'infra_projects_dataset_v1';

/**
 * Returns active projects from localStorage or seeds from INITIAL_DEMO_PROJECTS
 */
export function getStoredProjects(): InfraProject[] {
  if (typeof window === 'undefined') {
    return INITIAL_DEMO_PROJECTS;
  }
  try {
    const raw = localStorage.getItem(LOCAL_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (e) {
    console.warn('Could not read stored infra projects, using initial demo dataset:', e);
  }
  // Store default demo set if not present
  try {
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(INITIAL_DEMO_PROJECTS));
  } catch {
    // Ignore storage quota errors
  }
  return INITIAL_DEMO_PROJECTS;
}

/**
 * Updates stored projects in localStorage
 */
export function saveStoredProjects(projects: InfraProject[]): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(projects));
  } catch (e) {
    console.error('Failed to save projects to localStorage:', e);
  }
}

/**
 * Resets local dataset back to the authentic PAIMANA July 2026 snapshot demo set
 */
export function resetDemoDataset(): InfraProject[] {
  if (typeof window !== 'undefined') {
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(INITIAL_DEMO_PROJECTS));
  }
  return INITIAL_DEMO_PROJECTS;
}
